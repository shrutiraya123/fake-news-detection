import React, { useState } from 'react';
import { ToastContainer, toast } from 'react-toastify';
import 'react-toastify/dist/ReactToastify.css';

import Header from './header';
import { Container, Form, Button, Spinner } from 'react-bootstrap';
import Axios from 'axios';
import {
  Check2,
  X,
  ShieldCheck,
  Search,
  ArrowRight,
} from 'react-bootstrap-icons';

function CheckByTitle() {
  document.title = 'News Guardian | Check News by Title';

  const [inputNewsTitle, setNewsTitle] = useState('');
  const [predictedValue, setPredictedValue] = useState('');
  const [isLoading, setIsLoading] = useState(false);

  const handleSubmit = async (e) => {
    e.preventDefault();

    const title = inputNewsTitle.trim();

    if (!title) {
      toast.error('Please enter a news title first.');
      return;
    }

    setIsLoading(true);
    setPredictedValue('');

    try {
      const response = await Axios.post(
        'http://127.0.0.1:8000/api/usercheck/title/',
        {
          user_news: title,
        },
      );

      if (response.data.prediction === true) {
        setPredictedValue('True');

        toast.success('The title was predicted as real news.');
      } else {
        setPredictedValue('False');

        toast.error('The title was predicted as fake news.');
      }
    } catch (error) {
      console.error('Error submitting data:', error);

      toast.error('Something went wrong while checking the news.');
    } finally {
      setIsLoading(false);
    }
  };

  const handleInputChange = (e) => {
    setNewsTitle(e.target.value);

    // Clear an old result when the user starts typing again
    if (predictedValue) {
      setPredictedValue('');
    }
  };

  return (
    <>
      <Header activeContainer={2} />

      <main className='checker-page'>
        <Container>
          {/* HERO */}
          <section className='checker-hero'>
            <div className='checker-hero-icon'>
              <ShieldCheck />
            </div>

            <div className='checker-kicker'>NEWS VERIFICATION</div>

            <h1>
              Check a News
              <span> Title</span>
            </h1>

            <p>
              Enter a news headline and let News Guardian analyze it for you.
            </p>
          </section>

          {/* CHECKER CARD */}
          <section className='checker-card'>
            <div className='checker-card-header'>
              <div className='checker-input-icon'>
                <Search />
              </div>

              <div>
                <h2>Enter the news title</h2>

                <p>Paste or type the headline you want to verify.</p>
              </div>
            </div>

            <Form onSubmit={handleSubmit}>
              <Form.Group className='checker-form-group'>
                <Form.Label>News Title</Form.Label>

                <div className='checker-textarea-wrapper'>
                  <Form.Control
                    className='checker-textarea'
                    as='textarea'
                    rows={5}
                    value={inputNewsTitle}
                    placeholder='Example: Scientists discover a new breakthrough...'
                    onChange={handleInputChange}
                    disabled={isLoading}
                    maxLength={500}
                  />

                  <span className='character-count'>
                    {inputNewsTitle.length}/500
                  </span>
                </div>
              </Form.Group>

              <Button
                type='submit'
                className='checker-button'
                disabled={isLoading}
              >
                {isLoading ? (
                  <>
                    <Spinner animation='border' size='sm' />
                    Checking...
                  </>
                ) : (
                  <>
                    Check News
                    <ArrowRight />
                  </>
                )}
              </Button>
            </Form>

            {/* INFO */}
            <div className='checker-info'>
              <ShieldCheck />

              <span>
                The prediction is generated by the News Guardian classification
                system.
              </span>
            </div>
          </section>

          {/* RESULT */}
          {predictedValue && (
            <section
              className={`checker-result ${
                predictedValue === 'True' ? 'result-real' : 'result-fake'
              }`}
            >
              <div className='result-icon'>
                {predictedValue === 'True' ? <Check2 /> : <X />}
              </div>

              <div className='result-content'>
                <span className='result-label'>PREDICTION RESULT</span>

                <h2>
                  {predictedValue === 'True'
                    ? 'Predicted as Real News'
                    : 'Predicted as Fake News'}
                </h2>

                <p>
                  {predictedValue === 'True'
                    ? 'The system classified this news title as real.'
                    : 'The system classified this news title as fake.'}
                </p>
              </div>

              <div className='result-status'>
                {predictedValue === 'True' ? 'REAL' : 'FAKE'}
              </div>
            </section>
          )}
        </Container>
      </main>

      <ToastContainer
        position='bottom-right'
        autoClose={3500}
        theme='colored'
      />
    </>
  );
}

export default CheckByTitle;
